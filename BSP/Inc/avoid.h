#ifndef AVOID_H
#define AVOID_H

// 超声波避障逻辑
//
// 比赛规则要求"小车任何部件都不得与障碍物发生任何接触"才算成功避障，
// 撞到、撞开、撞移都算失败，所以这里的策略是"宁可保守"：
// 先刹车停稳，再决定往哪边绕，绝不带着速度贴上去。
//
// 建议动作 -> 典型处理
//   AVOID_FOLLOW       正常循迹
//   AVOID_SLOW         循迹，但降低速度
//   AVOID_BRAKE        立即刹车（短接制动）
//   AVOID_TURN_LEFT    原地左转
//   AVOID_TURN_RIGHT   原地右转
//   AVOID_BACK         后退
//
// 用法：
//   setup 里调用 Avoid_Init()
//   跑起来的时候：主循环里 switch (Avoid_Update()) 分派动作即可
//   停车/待机（不打算跑）的时候：每轮调用 Avoid_Sample()，
//   只测距不做动作，保证发车时用的距离是最新的

#include "main.h"
#include "hcsr04.h"

/* ==================== 探头配置 ==================== */

/* 是否使用中间的 U2 探头（PA10 / PA11）
 *   0 = 只用左右两个（当前装车状态）
 *   1 = 再加上中间一个，正前方的盲区会小很多
 *
 * 两个探头都向外斜安装时，波束角各有 ±15°(典型)，
 * 正前方会留下一块谁都照不到的区域，而障碍物偏偏最容易出现在正前方。
 * 比赛要求是"零接触"，所以如果实测发现正前方测不到，强烈建议把 U2 插上，
 * 把这个宏改成 1 —— 硬件和驱动都已支持，改一个数字就行。 */
#define AVOID_USE_CENTER 0

/* ==================== 距离阈值（厘米，按实车调整） ==================== */

/* 是否允许"后退"这个动作
 *   0 = 禁止（默认）
 *   1 = 允许
 *
 * 比赛规则："小车应自动按循迹线前进，一旦逆行，本轮比赛结束。"
 * 后退有可能被判成逆行，一旦判罚整轮比赛直接作废，风险远大于收益，
 * 所以默认关掉。关闭时"两侧都堵"会改成原地转向（原地转不算逆行）。
 * 只有确认裁判认可后退动作，才建议改成 1。 */
#define AVOID_ALLOW_BACK 0

/* 小于该距离立即触发避障：先刹车，再决定怎么绕。
 * 不要设得太小：采样有延迟（两路轮流测，单路约 80ms 才更新一次），
 * 再加上刹车距离，贴到十几厘米才动作就来不及了。 */
#define AVOID_STOP_CM 25

/* 小于该距离开始减速，但继续循迹。 */
#define AVOID_SLOW_CM 50

/* ==================== 时间参数（毫秒，按实车调整） ==================== */

/* 采样周期：每 AVOID_SAMPLE_MS 测一路，两路轮流则单路约 80ms 更新一次 */
#define AVOID_SAMPLE_MS 40

/* 刹车保持时间：先停稳，再转向，避免带着惯性蹭到障碍物 */
#define AVOID_BRAKE_MS 120

/* 一次转向的保持时间。太短会左右摇摆，太长会转过头，最需要按实车调 */
#define AVOID_TURN_MS 350

/* 后退保持时间 */
#define AVOID_BACK_MS 250

/* ==================== 建议动作 ==================== */

typedef enum
{
    AVOID_FOLLOW = 0, /* 交还给寻迹逻辑 */
    AVOID_SLOW,       /* 循迹但减速 */
    AVOID_BRAKE,      /* 立即刹车 */
    AVOID_TURN_LEFT,  /* 原地左转 */
    AVOID_TURN_RIGHT, /* 原地右转 */
    AVOID_BACK        /* 后退 */
} AvoidAction;

/* ==================== 函数 ==================== */

/* 初始化（内部会调用 HCSR04_Init） */
void Avoid_Init(void);

/* 每个主循环调用一次，返回当前建议的动作 */
AvoidAction Avoid_Update(void);

/* 取当前建议动作，不刷新状态 */
AvoidAction Avoid_GetAction(void);

/* 只做测距采样：不决策、不下发任何动作、不改状态机。
 * 停车/待机时在主循环里调用，让距离数据保持新鲜，
 * 这样发车（start）时第一次决策用的是当前距离，而不是停车前的旧值。
 * 采样节奏与 Avoid_Update() 内部一致：每 AVOID_SAMPLE_MS 测一路，
 * 左右轮流，单次测量最坏阻塞 HCSR04_TIMEOUT_US（8ms）。 */
void Avoid_Sample(void);

/* 取最近一次的距离读数（厘米，-1 表示无回波）
 * 正前方距离：装了中间探头就用中间那路，没装就取左右两路中较近的一个 */
int16_t Avoid_GetFrontCm(void);
int16_t Avoid_GetLeftCm(void);
int16_t Avoid_GetRightCm(void);

#endif
